"""
共通例外定義 (Domain Exceptions)
作成者: Lynn
----------------------------------
【役割】
アプリケーション全体で発生する「業務ルール上のエラー」を定義するファイルです。

【チームへのメリット】
1. エラーの分類が明確に: 
   「DBの接続エラー（システム障害）」と「在庫不足や状態不正（業務エラー）」を区別できます。
2. フロントへの通知を自動化: 
   これらの例外を `api_response_format` と組み合わせて使うことで、
   適切なHTTPステータスコードをフロントエンドに自動返却しやすくなります。
3. コードの可読性向上: 
   `raise NotFoundError("...")` と書くだけで、何が起きたのかが誰にでも伝わります。
"""

# app/domain/exception.py
class DomainError(Exception):
    """
    ドメイン層で発生するすべての例外の基底クラス（親クラス）です。
    独自の例外を追加する場合は、このクラスを継承してください。
    """
    pass

# --- エンティティ/値オブジェクトのバリデーション ---
class DomainValidationError(DomainError):
    """
    データの内容自体が正しくない場合に投げます。
    例: 「パレット数がマイナスになっている」「必須項目が空文字である」など。
    """
    pass

# --- サービス・リポジトリ層で共有されるエラー ---
class NotFoundError(DomainError):
    """
    要求されたリソース（データ）が見つからない場合に投げます。
    例: 「指定されたIDのタスクが存在しない」「ライン名がマスタにない」など。
    """
    pass

class InvalidStateError(DomainError):
    """
    現在の状態では許可されない操作を行おうとした場合に投げます。
    例: 「すでに完了したタスクをキャンセルしようとした」「停止中のラインを動かそうとした」など。
    """
    pass

class StaleWriteError(DomainError):
    """
    楽観的ロック（排他制御）によるエラーです。
    例: 「編集を開始してから保存するまでの間に、他のユーザーがデータを更新してしまった（版数/revの不一致）」など。
    """
    pass